package site

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

var (
	caddyHostRe = regexp.MustCompile(`^([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$`)
	caddyRootRe = regexp.MustCompile(`^/[A-Za-z0-9._/-]+$`)
)

// Path-class matchers, equivalent to ClassOf (git wins over the others,
// which the generated route gets by applying it last).
const (
	reGit     = `^/[^/_][^/]*/[^/]*\.git/`
	reRaw     = `^/[^/_][^/]*/[^/]*/raw/`
	reMedia   = `^/[^/_][^/]*/[^/]*/media/`
	reDL      = `^/[^/_][^/]*/[^/]*/dl/`
	reArchive = `^/[^/_][^/]*/[^/]*/archive/`
)

// CaddySite generates the Caddy site block that serves a built site at
// root for host with exactly the header contract of ContractHeaders (the
// preview server). Verify a deployment with CheckContract.
func CaddySite(host, root string) (string, error) {
	if !caddyHostRe.MatchString(host) {
		return "", fmt.Errorf("caddy: invalid host %q", host)
	}
	if !caddyRootRe.MatchString(root) || strings.Contains(root, "..") {
		return "", fmt.Errorf("caddy: invalid root %q", root)
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	common := func(indent string) {
		w(indent+"X-Content-Type-Options %s", q("nosniff"))
		w(indent+"Referrer-Policy %s", q("no-referrer"))
		w(indent+"X-Frame-Options %s", q("DENY"))
		w(indent+"Cross-Origin-Opener-Policy %s", q("same-origin"))
		w(indent+"Cross-Origin-Resource-Policy %s", q("same-origin"))
		w(indent+"Permissions-Policy %s", q(PermissionsPolicy))
	}

	w("# Generated by `fpp caddy-site -host %s -root %s`. Do not edit:", host, root)
	w("# regenerate it. It implements fpp's header contract")
	w("# (internal/site/serve.go); check a deployment with `fpp check-contract`.")
	w("http://%s:8080 {", host)
	w("\troot * %s", root)
	w("")
	w("\t@method not method GET HEAD")
	w("\thandle @method {")
	w("\t\theader Allow %s", q("GET, HEAD"))
	w("\t\theader -Server")
	w("\t\trespond 405")
	w("\t}")
	w("")
	for _, m := range []struct{ name, re string }{
		{"git", reGit}, {"raw", reRaw}, {"media", reMedia}, {"dl", reDL}, {"archive", reArchive},
	} {
		w("\t@%s path_regexp %s", m.name, m.re)
	}
	exts := sortedKeys(siteTypes)
	for _, ext := range exts {
		if ext != "" {
			w("\t@site%s path *%s", strings.ReplaceAll(ext, ".", "_"), ext)
		}
	}
	w("\t@site_dir path */")
	for _, ext := range sortedKeys(mediaTypes) {
		w("\t@media%s {", strings.ReplaceAll(ext, ".", "_"))
		w("\t\tpath_regexp %s", reMedia)
		w("\t\tpath *%s", ext)
		w("\t}")
	}
	w("\t@targz {")
	w("\t\tpath_regexp %s", reArchive)
	w("\t\tpath *.tar.gz")
	w("\t}")
	w("\t@static path /_static/*")
	w("")
	w("\t# Later header directives override earlier ones (route keeps order).")
	w("\t# Header deletions are deferred by Caddy (applied when the response is")
	w("\t# written), so they stay in their own directives: a block containing a")
	w("\t# deletion is deferred as a whole and would override everything after it.")
	w("\troute {")
	w("\t\theader -Server")
	w("\t\theader {")
	common("\t\t\t")
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t\tContent-Security-Policy %s", q(SiteCSP))
	w("\t\t\tContent-Type %s", q("application/octet-stream"))
	w("\t\t}")
	for _, ext := range exts {
		m := "@site" + strings.ReplaceAll(ext, ".", "_")
		if ext == "" {
			m = "@site_dir"
		}
		w("\t\theader %s Content-Type %s", m, q(siteTypes[ext]))
	}
	w("\t\theader @static Cache-Control %s", q(CacheImmutable))
	w("\t\theader @raw {")
	w("\t\t\tContent-Type %s", q("text/plain; charset=utf-8"))
	w("\t\t\tContent-Security-Policy %s", q(RawCSP))
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t}")
	w("\t\theader @media {")
	w("\t\t\tContent-Type %s", q("application/octet-stream"))
	w("\t\t\tContent-Security-Policy %s", q(MediaCSP))
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t}")
	for _, ext := range sortedKeys(mediaTypes) {
		w("\t\theader @media%s Content-Type %s", strings.ReplaceAll(ext, ".", "_"), q(mediaTypes[ext]))
	}
	w("\t\theader @dl {")
	w("\t\t\tContent-Type %s", q("application/octet-stream"))
	w("\t\t\tContent-Disposition %s", q("attachment"))
	w("\t\t\tContent-Security-Policy %s", q(RawCSP))
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t}")
	w("\t\theader @archive {")
	w("\t\t\tContent-Type %s", q("application/zip"))
	w("\t\t\tContent-Disposition %s", q("attachment"))
	w("\t\t\tContent-Security-Policy %s", q(RawCSP))
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t}")
	w("\t\theader @targz Content-Type %s", q("application/gzip"))
	w("\t\theader @git {")
	w("\t\t\tContent-Type %s", q("application/octet-stream"))
	w("\t\t\tContent-Security-Policy %s", q(RawCSP))
	w("\t\t\tCache-Control %s", q(CacheShort))
	w("\t\t}")
	w("\t\theader @git -Content-Disposition")
	w("\t\tfile_server {")
	w("\t\t\thide .fpp-site")
	w("\t\t}")
	w("\t}")
	w("")
	w("\thandle_errors 404 {")
	w("\t\theader -Server")
	w("\t\theader -Content-Disposition")
	w("\t\theader {")
	common("\t\t\t")
	w("\t\t\tCache-Control %s", q("no-store"))
	w("\t\t\tContent-Security-Policy %s", q(SiteCSP))
	w("\t\t\tContent-Type %s", q("text/html; charset=utf-8"))
	w("\t\t}")
	w("\t\trewrite * /404.html")
	w("\t\tfile_server")
	w("\t}")
	w("\thandle_errors {")
	w("\t\theader -Server")
	w("\t\trespond {err.status_code}")
	w("\t}")
	w("}")
	return b.String(), nil
}

func q(s string) string { return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"` }

func sortedKeys(m map[string]string) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}
