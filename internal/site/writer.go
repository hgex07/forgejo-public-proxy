package site

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path"
)

// writer writes the staged site through os.Root, so no path (whatever the
// repo contents) can resolve outside the output directory. Files are never
// overwritten: a second write to the same path is an error, which catches
// route collisions.
type writer struct {
	root  *os.Root
	total int64
	limit int64
	dirs  map[string]bool
	files map[string]bool
}

// Site files are public by definition; set modes explicitly so the process
// umask (077 for fpp's private state) does not apply.
const (
	fileMode = 0o644
	dirMode  = 0o755
)

// MarkerFile identifies a directory created by fpp (safe to replace).
const MarkerFile = ".fpp-site"

func newWriter(dir string, limit int64) (*writer, error) {
	if err := os.Mkdir(dir, dirMode); err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(dir)
	if err != nil {
		return nil, err
	}
	w := &writer{root: root, limit: limit, dirs: map[string]bool{".": true}, files: map[string]bool{}}
	if err := root.Chmod(".", dirMode); err != nil {
		return nil, err
	}
	return w, w.write(MarkerFile, []byte("generated by fpp; this directory is replaced on every build\n"))
}

func (w *writer) Close() error { return w.root.Close() }

func (w *writer) mkdirs(dir string) error {
	if w.dirs[dir] {
		return nil
	}
	if w.files[dir] {
		return fmt.Errorf("site: %q is both a file and a directory", dir)
	}
	if err := w.mkdirs(path.Dir(dir)); err != nil {
		return err
	}
	if err := w.root.Mkdir(dir, dirMode); err != nil && !errors.Is(err, fs.ErrExist) {
		return err
	}
	if err := w.root.Chmod(dir, dirMode); err != nil {
		return err
	}
	w.dirs[dir] = true
	return nil
}

func (w *writer) claim(name string, size int64) error {
	if !fs.ValidPath(name) || name == "." {
		return fmt.Errorf("site: invalid output path %q", name)
	}
	if w.files[name] || w.dirs[name] {
		return fmt.Errorf("site: output path %q written twice", name)
	}
	if w.total+size > w.limit {
		return fmt.Errorf("site: output exceeds max_site_bytes (%d)", w.limit)
	}
	if err := w.mkdirs(path.Dir(name)); err != nil {
		return err
	}
	w.files[name] = true
	w.total += size
	return nil
}

func (w *writer) write(name string, data []byte) error {
	if err := w.claim(name, int64(len(data))); err != nil {
		return err
	}
	f, err := w.root.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, fileMode)
	if err != nil {
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Chmod(fileMode); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// create opens a new file for streaming; size accounting happens on Close.
func (w *writer) create(name string) (*countingFile, error) {
	if err := w.claim(name, 0); err != nil {
		return nil, err
	}
	f, err := w.root.OpenFile(name, os.O_WRONLY|os.O_CREATE|os.O_EXCL, fileMode)
	if err != nil {
		return nil, err
	}
	if err := f.Chmod(fileMode); err != nil {
		f.Close()
		return nil, err
	}
	return &countingFile{f: f, w: w}, nil
}

type countingFile struct {
	f *os.File
	w *writer
	n int64
}

func (c *countingFile) Write(p []byte) (int, error) {
	if c.w.total+int64(len(p)) > c.w.limit {
		return 0, fmt.Errorf("site: output exceeds max_site_bytes (%d)", c.w.limit)
	}
	n, err := c.f.Write(p)
	c.w.total += int64(n)
	c.n += int64(n)
	return n, err
}

func (c *countingFile) Close() error { return c.f.Close() }

var _ io.WriteCloser = (*countingFile)(nil)

// link hardlinks an already written file to a new path (same content, no
// extra bytes counted).
func (w *writer) link(existing, name string) error {
	if !w.files[existing] {
		return fmt.Errorf("site: link source %q was not written", existing)
	}
	if err := w.claim(name, 0); err != nil {
		return err
	}
	return w.root.Link(existing, name)
}
